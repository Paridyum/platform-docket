#!/usr/bin/env bash
#
# PreToolUse guard — blocks edits that violate ADR-0001 and ADR-0002.
#
# This is the enforcement layer that does not depend on GitHub's plan. A hook that
# denies a tool call cannot be reasoned around by the agent, cannot be forgotten
# after compaction, and stops the violation before it is written rather than after
# it is pushed. See ADR-0007.
#
# Denies:
#   1. Any write into a vendored .paridyum/knowledge/ snapshot (read-only, ADR-0001)
#   2. Any edit to generated code (C-0004)
#   3. Any edit to a knowledge artifact whose frontmatter says status: locked,
#      EXCEPT the legal supersession edit (ADR-0002)
#
# Escalates to "ask":
#   4. Any edit to a governance file — the layer that enforces everything else (C-0004)
#
# Input: hook JSON on stdin. Output: permissionDecision JSON on stdout.
# Exits 0 always — a crashed guard must not wedge the session. Failures are
# reported as "allow" with a warning rather than a hard stop, because a guard that
# blocks everything on a jq syntax error is worse than one that fails open and says so.

set -uo pipefail

deny() {
  jq -n --arg r "$1" '{
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "deny",
      permissionDecisionReason: $r
    }
  }'
  exit 0
}

command -v jq >/dev/null 2>&1 || {
  echo "paridyum guard: jq not installed; locked-decision enforcement is OFF" >&2
  exit 0
}

payload="$(cat)"

# Validate once, quietly. jq's own parse errors are repeated per invocation and say
# nothing useful to the operator, so they are suppressed in favour of one clear line.
if ! jq -e . >/dev/null 2>&1 <<<"$payload"; then
  echo "paridyum guard: unparseable hook input; locked-decision enforcement SKIPPED for this call" >&2
  exit 0
fi

tool="$(jq -r '.tool_name // empty'            <<<"$payload" 2>/dev/null)"
path="$(jq -r '.tool_input.file_path // empty' <<<"$payload" 2>/dev/null)"

[[ -z "$path" ]] && exit 0
case "$tool" in Write|Edit|NotebookEdit) ;; *) exit 0 ;; esac

# --------------------------------------------------------------------------
# 1. Vendored knowledge is read-only (ADR-0001)
# --------------------------------------------------------------------------
if [[ "$path" == *"/.paridyum/knowledge/"* ]]; then
  deny "ADR-0001: .paridyum/knowledge/ is a read-only vendored snapshot. Edits here are destroyed on the next 'forge knowledge sync'. Make the change in the Paridyum/knowledge repository instead, then re-sync."
fi

# --------------------------------------------------------------------------
# 2. Generated code is regenerated, never edited (C-0004)
# --------------------------------------------------------------------------
if [[ -f "$path" ]] && head -20 "$path" 2>/dev/null | grep -qiE '@generated|DO NOT EDIT|code generated by'; then
  deny "C-0004: $(basename "$path") is generated code and must not be hand-edited — the next regeneration silently discards the change. Edit the generator or its input schema instead."
fi

# --------------------------------------------------------------------------
# 3. Governance files escalate to the user rather than blocking (C-0004)
#
# These are legitimately edited — this repository's own CI and CODEOWNERS were
# written by an agent. But they are the layer that enforces everything else, so
# an agent must not modify them unattended. "ask" keeps the work possible while
# guaranteeing a human sees the diff.
# --------------------------------------------------------------------------
# The enumeration in C-0004 names the file kinds; the rule it states is general — "the
# layer that enforces everything else — a change here can silently disable every other
# control". The entries below marked (extends C-0004) are that rule applied to the
# enforcement machinery itself, which the original list did not reach. Escalating more
# than the constitution enumerates fails safe: the worst case is one extra prompt.
governance_reason=""
case "$path" in
  *"/.github/workflows/"*)      governance_reason="a CI workflow — the layer that enforces every other rule" ;;
  *"/CODEOWNERS"|*"/.github/CODEOWNERS") governance_reason="CODEOWNERS — it decides who must review changes" ;;
  *"/LICENSE"|*"/LICENSE."*)    governance_reason="the licence" ;;
  *"/.claude/settings.json"|*"/.claude/settings.local.json")
                                governance_reason="Claude Code settings — including which enforcement hooks run" ;;
  *"/hooks/hooks.json")         governance_reason="the hook registry — disabling a hook disables enforcement" ;;
  *"/hooks/"*.sh)               governance_reason="an enforcement hook itself — hooks.json decides which guards run, this decides what they do. A guard edited into a no-op stays registered and reports success while enforcing nothing, so this is the least visible way to disable every lock at once (extends C-0004)" ;;
  *"/.claude-plugin/marketplace.json"|*"/.claude-plugin/plugin.json")
                                governance_reason="the plugin manifest — it decides whether the enforcement hooks are distributed and loaded at all (ADR-0007) (extends C-0004)" ;;
  *"/scripts/check-"*.sh|*"/scripts/install-hooks.sh")
                                governance_reason="a gate script — CI and the pre-commit hook execute it directly, so weakening it weakens every check simultaneously (ADR-0002) (extends C-0004)" ;;
  *"/.gitattributes")           governance_reason=".gitattributes — line-ending normalisation (ADR-0006)" ;;
  *"/knowledge.schema.json")    governance_reason="the knowledge schema — it defines what 'locked' means" ;;
esac

# Deliberately NOT escalated: bootstrap.sh / bootstrap.ps1 and scripts/lib/*. They
# provision a workstation rather than enforce a rule, and they are edited far more often
# than the gate is. C-0004's own warning applies — "escalating routine commands trains
# the habit of approving without reading, which is how a real one gets waved through".

if [[ -n "$governance_reason" ]]; then
  jq -n --arg r "C-0004: this edits $governance_reason. Governance changes are permitted but never unattended — confirm the diff is intended and does not weaken enforcement." '{
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "ask",
      permissionDecisionReason: $r
    }
  }'
  exit 0
fi

# --------------------------------------------------------------------------
# 3b. Creating a NEW service is the irreversible architectural act (RFC-0002)
# --------------------------------------------------------------------------
# ADR-0013 rejected a PreToolUse guard on implementation, and was right: "an agent cannot
# know at first file-write whether the eventual diff will be significant, so the hook
# would fire constantly on trivial work and be disabled."
#
# That reasoning does not reach here, and the distinction is the whole justification for
# this block. Creating a service IS knowable at the first write — a new manifest.yaml or
# a new Cargo.toml under a svc-/platform-/lib-/tool- path is unambiguous — and it is the
# act that decides a boundary, which is the expensive and effectively permanent decision
# (ANTI-0001, ANTI-0006). Ordinary editing is untouched, so this fires once per service
# rather than constantly, and does not train the habit of waving prompts through.
#
# `ask`, never `deny`. ADR-0008: "a guard that denies every dangerous thing is disabled
# within a week." An exploratory spike is legitimate — ADR-0013 protects it explicitly by
# making pr.design_artifact_predates_implementation a warning — so a human may simply
# say yes. What must not happen is a service appearing without anyone noticing.
#
# Only fires on CREATE. Editing an existing manifest is routine and is covered by
# docs.manifest_schema_valid and the ownership checks instead.
if [[ ! -e "$path" ]]; then
  new_service_reason=""
  case "$path" in
    */manifest.yaml)
      new_service_reason="a new manifest.yaml — this declares a new repository's identity, ownership and dependencies" ;;
    */svc-*/Cargo.toml|*/platform-*/Cargo.toml|*/lib-*/Cargo.toml|*/tool-*/Cargo.toml)
      new_service_reason="a new crate in a classed repository — this creates a deployable and its boundary" ;;
  esac
  if [[ -n "$new_service_reason" ]]; then
    jq -n --arg r "RFC-0002: this creates $new_service_reason. A service boundary is the most expensive decision to reverse — two services owning one table (ANTI-0001) is effectively permanent once shipped. Before continuing, confirm: which bounded context is this, what does it exclusively own, and which accepted RFC or ADR decided that? If the decomposition has not been done, run the decompose-spec skill instead of creating this file. Spikes are legitimate — say yes and carry on if that is what this is." '{
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "ask",
        permissionDecisionReason: $r
      }
    }'
    exit 0
  fi
fi

# --------------------------------------------------------------------------
# 4. Locked artifacts are immutable except for supersession (ADR-0002)
# --------------------------------------------------------------------------

# Only applies to knowledge artifacts, and only to files that already exist —
# creating a new ADR must stay unobstructed.
[[ -f "$path" ]] || exit 0
# This list must equal the set of types declaring `immutable_when_locked: true` in
# artifact-registry.yaml (ADR-0022). It is hardcoded rather than read from the registry
# because this hook runs on EVERY tool call and must stay fast and dependency-free — a
# YAML parse per keystroke is a hook people disable. That makes it the one site ADR-0022
# could not derive, so it is stated as a rule with the registry named.
#
# `requirements/` was MISSING and that was a real hole, not a stylistic gap. Section 3 of
# check-knowledge.sh has always protected requirements/, so layer 1 and layer 2 of ADR-0007's
# enforcement ladder disagreed about which artifacts are immutable — and layer 1 is the one
# CLAUDE.md describes as impossible to reason around. A locked REQ- could be rewritten in
# place, in-session, and this guard permitted it. Same shape as the `superseded` hole
# recorded below: the guard was narrower than the rule it was enforcing.
#
# `rfc/` and `runbooks/` are deliberately absent, matching `immutable_when_locked: false`
# for those two types. Including them would fail safe — the status check below decides the
# outcome either way — but it would also contradict the registry, and a guard that disagrees
# with the declared rule is how the next hole gets argued into existence.
case "$path" in
  *"/constitution/"*.md|*"/adr/"*.md|*"/standards/"*.md|*"/patterns/"*.md \
  |*"/anti-patterns/"*.md|*"/requirements/"*.md|*"/bets/"*.md \
  |*"/glossary/"*.md|*"/markets/"*.md) ;;
  *) exit 0 ;;
esac

# Read frontmatter only: awk stops at the closing delimiter so this stays cheap
# on large files and cannot be fooled by the word "locked" in the prose body.
status="$(awk 'NR==1 && $0!="---"{exit} NR>1 && $0=="---"{exit} /^status:/{print $2; exit}' "$path" 2>/dev/null)"
# `superseded` is guarded too, and this was a real hole: protection used to lapse at
# exactly the moment an artifact became purely historical. ADR-0002's central sentence
# was inverted in a test and this guard permitted it. A superseded artifact needs MORE
# protection than a locked one — it is the record of what was true when the existing
# code was written, which the new-decision skill calls the entire value of the archive.
case "$status" in locked|superseded) ;; *) exit 0 ;; esac

artifact_id="$(awk 'NR==1 && $0!="---"{exit} NR>1 && $0=="---"{exit} /^id:/{print $2; exit}' "$path" 2>/dev/null)"
artifact_id="${artifact_id:-$(basename "$path")}"

# A whole-file overwrite of a locked artifact is never legal.
if [[ "$tool" == "Write" ]]; then
  deny "ADR-0002: $artifact_id is LOCKED and cannot be overwritten. To change it, write a new artifact that supersedes it and set 'superseded_by' on this one. Editing a locked artifact in place destroys the record of what was true when the existing code was written."
fi

# For Edit, permit the one legal mutation: marking the artifact superseded.
old="$(jq -r '.tool_input.old_string // empty' <<<"$payload")"
new="$(jq -r '.tool_input.new_string // empty' <<<"$payload")"

is_supersession_edit() {
  # Every changed line must be a status: or superseded_by: frontmatter field.
  local combined; combined="$(printf '%s\n%s\n' "$old" "$new")"
  [[ -n "$(tr -d '[:space:]' <<<"$combined")" ]] || return 1
  while IFS= read -r line; do
    [[ -z "${line// /}" ]] && continue
    [[ "$line" =~ ^(status|superseded_by|locked_at): ]] || return 1
  done <<<"$combined"
  return 0
}

if is_supersession_edit; then
  exit 0   # legal: recording that this artifact has been superseded
fi

# ADR-0031: an appended, dated erratum. The second legal mutation.
#
# THIS GUARD IS WEAKER THAN THE GATE AND THAT IS STATED RATHER THAN HIDDEN. Layer 3 diffs
# against the committed version and can prove the body is byte-identical; this hook has only
# the Edit's own old/new strings and must stay dependency-free, so it can prove one thing:
# the edit is strictly additive at its anchor. An edit that passes here and rewrites the body
# elsewhere is still caught by check-knowledge.sh section 3 — the disagreement is fail-safe in
# direction, and ADR-0031 cost 2 records it as a real cost rather than a rounding error.
is_errata_edit() {
  [[ "$new" == "$old"* ]] || return 1          # additive at the anchor: nothing replaced
  local added="${new#"$old"}"
  [[ -n "$(tr -d '[:space:]' <<<"$added")" ]] || return 1
  # Either the addition opens the errata section, or the anchor is already inside one.
  grep -qE '^## Errata[[:space:]]*$' <<<"$added" && return 0
  grep -qE '^## Errata[[:space:]]*$' <<<"$old"   && return 0
  return 1
}

if is_errata_edit; then
  exit 0   # legal: appending a dated erratum, body untouched
fi

deny "ADR-0002: $artifact_id is LOCKED. Its content is immutable — the only permitted edit is setting 'status' / 'superseded_by' to record supersession. To change the decision, write a new artifact that supersedes this one. If the task genuinely requires contradicting $artifact_id, stop and raise it rather than working around it."
