//! Opening a record by asking, rather than by editing YAML.

use crate::adapters::console;
use crate::adapters::registry::Registry;
use crate::config::Paths;
use crate::domain::personnel::Question;
use anyhow::{Context, Result, bail};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::{BufRead, Write};

/// Sensible starting values, so a blank answer is usually right.
///
/// Only where a default is genuinely safe. There is no default for a name, a
/// date or an institution — an invented one would be written into an agreement.
fn default_for(path: &str) -> Option<&'static str> {
    match path {
        "identity.pronouns" => Some("they/them/their"),
        "engagement.work_arrangement" => Some("Remote"),
        "engagement.stage" => Some("offered"),
        "education.currently_enrolled" => Some("true"),
        "equipment.issued" | "reference.requested" => Some("false"),
        _ => None,
    }
}

/// Whether this field takes true/false.
fn is_flag(path: &str) -> bool {
    matches!(
        path,
        "education.currently_enrolled"
            | "education.academic_credit"
            | "education.institution_requires_noc"
            | "education.institution_requires_certificate"
            | "equipment.issued"
            | "reference.requested"
    )
}

/// Ask the questions this class declares, and return the answers.
///
/// Required questions come first, and after them the operator is offered a way
/// out: the shortest useful session answers only what the class requires and
/// leaves the rest to be filled in later. An interrogation of fifty fields is
/// not a wizard.
///
/// # Errors
/// Fails if the class is unknown or the terminal cannot be read.
pub fn interview(
    registry: &Registry,
    class_name: &str,
    out: &mut impl Write,
    input: &mut impl BufRead,
) -> Result<BTreeMap<String, String>> {
    let Some(class) = registry.catalogue.class(class_name) else {
        let known: Vec<&str> = registry
            .catalogue
            .classes
            .iter()
            .map(|c| c.class.as_str())
            .collect();
        bail!(
            "unknown person class {class_name:?}; declared: {}",
            known.join(" ")
        );
    };
    let questions = crate::domain::personnel::questions(&registry.catalogue, class);
    let (required, optional): (Vec<&Question>, Vec<&Question>) =
        questions.iter().partition(|q| q.required);

    writeln!(out, "\nOpening a record for a {class_name}.")?;
    writeln!(out, "{}", class.description.trim())?;
    writeln!(
        out,
        "\n{} required, {} optional. Blank accepts the default where one is \
         shown; otherwise it leaves the field unset.",
        required.len(),
        optional.len()
    )?;

    let mut answers = BTreeMap::new();
    let mut group = String::new();
    for q in required.iter().chain(optional.iter()) {
        if q.group != group {
            group.clear();
            group.push_str(&q.group);
            writeln!(out, "\n-- {} --", q.group.replace('_', " "))?;
        }
        let label = q
            .path
            .rsplit('.')
            .next()
            .unwrap_or(&q.path)
            .replace('_', " ");
        let answer = console::ask(
            out,
            input,
            &label,
            &q.purpose,
            q.required,
            default_for(&q.path),
        )?;
        if let Some(v) = answer {
            answers.insert(q.path.clone(), v);
        }
        // Offered once, after the last required question.
        if q.required && required.last().is_some_and(|l| l.path == q.path) {
            writeln!(out, "\nEverything required is answered.")?;
            if !console::confirm(out, input, "Fill in the optional fields now?", false)? {
                writeln!(
                    out,
                    "Stopping here. The rest can be edited in the record, or asked \
                     again with --interactive."
                )?;
                break;
            }
        }
    }
    Ok(answers)
}

/// Render answers as the person record.
///
/// Written from the catalogue rather than by copying the template, so the file
/// carries each field's stated purpose as a comment next to it. Both paths
/// exist: `docket new` still copies `_TEMPLATE.yaml`, because removing a
/// working path to add one is what ADR-0054 forbids.
#[must_use]
pub fn to_yaml(
    registry: &Registry,
    class_name: &str,
    answers: &BTreeMap<String, String>,
) -> String {
    let mut out = String::from(
        "# GENERATED by `docket new --interactive`. Edit freely.\n\
         #\n\
         # Every field is declared in registry/fields.yaml with a stated purpose,\n\
         # reproduced below. A field not declared there is rejected by\n\
         # `docket check`, and so is one your class does not permit.\n\
         version: 1\n",
    );
    let purposes: BTreeMap<&str, &str> = registry
        .catalogue
        .fields
        .iter()
        .map(|f| (f.path.as_str(), f.purpose.trim()))
        .collect();

    // Group in the order the catalogue declares, so the file reads the way the
    // interview ran.
    let mut groups: Vec<&str> = Vec::new();
    for f in &registry.catalogue.fields {
        if !groups.contains(&f.group.as_str()) {
            groups.push(&f.group);
        }
    }

    for group in groups {
        let mut lines: Vec<(String, String)> = Vec::new();
        for (path, value) in answers {
            let Some((head, tail)) = path.split_once('.') else {
                continue;
            };
            if registry
                .catalogue
                .fields
                .iter()
                .any(|f| f.path == *path && f.group == group)
            {
                lines.push((format!("{head}|{tail}"), value.clone()));
            }
        }
        if lines.is_empty() {
            continue;
        }
        // One YAML mapping per top-level key present in this group.
        let mut heads: Vec<&str> = Vec::new();
        for (k, _) in &lines {
            let head = k.split('|').next().unwrap_or_default();
            if !heads.contains(&head) {
                heads.push(head);
            }
        }
        for head in heads {
            let _ = writeln!(out, "\n{head}:");
            for (k, v) in &lines {
                let mut parts = k.split('|');
                if parts.next() != Some(head) {
                    continue;
                }
                let tail = parts.next().unwrap_or_default();
                let full = format!("{head}.{tail}");
                if let Some(p) = purposes.get(full.as_str()) {
                    for line in wrap(p, 68) {
                        let _ = writeln!(out, "  # {line}");
                    }
                }
                let _ = writeln!(out, "  {tail}: {}", scalar(&full, v));
            }
        }
    }
    let _ = write!(out, "\n# class: {class_name}\n");
    out
}

/// Quote a value unless it is a bare flag or number.
fn scalar(path: &str, value: &str) -> String {
    if is_flag(path) {
        let v = value.trim().to_lowercase();
        return if matches!(v.as_str(), "y" | "yes" | "true" | "1") {
            "true".to_owned()
        } else {
            "false".to_owned()
        };
    }
    if path == "identity.pronouns" {
        // Written as subject/object/possessive, expanded into the block the
        // templates read.
        let parts: Vec<&str> = value.split('/').map(str::trim).collect();
        let get = |i: usize, fallback: &str| -> String {
            parts
                .get(i)
                .filter(|p| !p.is_empty())
                .map_or_else(|| fallback.to_owned(), |p| (*p).to_owned())
        };
        return format!(
            "\n    subject: {}\n    object: {}\n    possessive: {}",
            get(0, "they"),
            get(1, "them"),
            get(2, "their")
        );
    }
    if value.parse::<i64>().is_ok() && !value.starts_with('0') {
        return value.to_owned();
    }
    // Quote anything that YAML might read as something else.
    format!("{value:?}")
}

/// Wrap prose for a comment.
fn wrap(text: &str, width: usize) -> Vec<String> {
    let mut lines = Vec::new();
    let mut current = String::new();
    for word in text.split_whitespace() {
        if !current.is_empty() && current.len() + 1 + word.len() > width {
            lines.push(std::mem::take(&mut current));
        }
        if !current.is_empty() {
            current.push(' ');
        }
        current.push_str(word);
    }
    if !current.is_empty() {
        lines.push(current);
    }
    lines
}

/// Write the record, refusing to overwrite one that exists.
///
/// # Errors
/// Fails if a record is already there, or it cannot be written.
pub fn write_record(paths: &Paths, slug: &str, body: &str) -> Result<()> {
    let path = paths.person(slug);
    if path.exists() {
        bail!("a record already exists at {}", path.display());
    }
    std::fs::create_dir_all(&paths.people)
        .with_context(|| format!("creating {}", paths.people.display()))?;
    std::fs::write(&path, body).with_context(|| format!("writing {}", path.display()))?;
    Ok(())
}
