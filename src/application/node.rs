//! What a node holds, what replicates, and how a cold spare is brought up.
//!
//! ADR-0072. The operator asked how to survive losing a laptop; measuring the
//! answer showed the key was never the exposure -- RUN-0004 already keeps the
//! one age key in a password manager -- and that the store was.
//!
//! This module answers two questions the store could not previously answer:
//! *what dies with this machine*, and *can a different machine bring it back*.

use crate::adapters::{crypt, store};
use crate::config::Paths;
use crate::domain::chain;
use anyhow::{Context, Result, bail};
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

/// What replication a path in the store is entitled to.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Disposition {
    /// Ciphertext. Belongs in the off-host store (ADR-0071).
    Replicate,
    /// Plaintext that a backup must carry, and only ever as ciphertext.
    /// Reaches the off-host store through `vault backup`, never directly.
    ViaBundle,
    /// Must never leave this machine.
    Never,
    /// Nobody has said. ADR-0072 decision 3's sibling: the failure this exists
    /// to catch is a directory added later that lands in no list at all.
    Unclassified,
}

impl Disposition {
    /// One word for a report.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Replicate => "replicate",
            Self::ViaBundle => "via-bundle",
            Self::Never => "never",
            Self::Unclassified => "UNCLASSIFIED",
        }
    }
}

/// The declared table. Every top-level entry under `store/` must appear here.
///
/// **Inverted on purpose.** `vault::syncable` names an upload directory and a
/// never-upload list, which answers "may I upload this?" and cannot answer
/// "is anything unaccounted for?". A directory added next year appears in
/// neither list and is silently outside both the backup and the prohibition.
/// Enumerating the store and demanding a verdict for each entry is the only
/// form of this check that fails when someone forgets.
fn declared() -> BTreeMap<&'static str, Disposition> {
    let mut m = BTreeMap::new();
    // Ciphertext, and the only thing meant to be uploaded.
    m.insert("vault", Disposition::Replicate);
    // The irreplaceable half. Plaintext here, ciphertext once `vault backup`
    // has run; the bundle is what reaches the off-host store.
    m.insert("register", Disposition::ViaBundle);
    m.insert("issued", Disposition::ViaBundle);
    m.insert("scans", Disposition::ViaBundle);
    // Per-person keys. ADR-0069: a restorable key is a key nobody can prove
    // was destroyed, and a versioned store retains what it is told to delete.
    m.insert("keys", Disposition::Never);
    // ADR-0051's opaque folder naming is defeated by uploading the index that
    // maps opaque ids back to names.
    m.insert("index", Disposition::Never);
    // Derived from the register, regenerated by `docket team`.
    m.insert("exports", Disposition::Never);
    // The store lock. Machine-local by definition; replicating it would hand a
    // spare a lock held by a machine that no longer exists.
    m.insert(".writing.lock", Disposition::Never);
    m
}

/// One line of `docket store status`.
#[derive(Debug, Clone)]
pub struct Item {
    /// Entry name under `store/`.
    pub name: String,
    /// What replication it is entitled to.
    pub disposition: Disposition,
    /// Bytes it occupies.
    pub bytes: u64,
}

/// Classify everything currently in the store.
///
/// # Errors
/// Fails if the store cannot be read.
pub fn classify(paths: &Paths) -> Result<Vec<Item>> {
    let table = declared();
    if !paths.store.exists() {
        return Ok(Vec::new());
    }
    let mut items = Vec::new();
    for entry in
        fs::read_dir(&paths.store).with_context(|| format!("reading {}", paths.store.display()))?
    {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let disposition = table
            .get(name.as_str())
            .copied()
            .unwrap_or(Disposition::Unclassified);
        items.push(Item {
            bytes: size_of(&entry.path())?,
            name,
            disposition,
        });
    }
    items.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(items)
}

/// Recursive size, so the report can say how much is at stake.
fn size_of(path: &Path) -> Result<u64> {
    let meta = fs::symlink_metadata(path)?;
    if !meta.is_dir() {
        return Ok(meta.len());
    }
    let mut total: u64 = 0;
    for entry in fs::read_dir(path)? {
        total = total.saturating_add(size_of(&entry?.path())?);
    }
    Ok(total)
}

/// Whether `vault backup` has run since the register last changed.
///
/// Answers "what dies with this machine" rather than "what could be uploaded":
/// a `ViaBundle` path with no bundle behind it is unreplicated, however
/// carefully the never-list is observed.
///
/// # Errors
/// Fails if the store cannot be read.
pub fn unreplicated(paths: &Paths) -> Result<Vec<String>> {
    let bundle = paths.store.join("vault").join("_register");
    let mut out = Vec::new();
    for item in classify(paths)? {
        let missing = match item.disposition {
            Disposition::ViaBundle => !bundle.exists(),
            Disposition::Unclassified => true,
            Disposition::Replicate | Disposition::Never => false,
        };
        if missing && item.bytes > 0 {
            out.push(item.name);
        }
    }
    Ok(out)
}

/// Bring a cold spare up from a register bundle and the estate key.
///
/// ADR-0072 decision 6, adopting ADR-0071 §3: *"a backup that has never been
/// restored is a belief, not a control"*. Restoring into a **non-empty**
/// register is refused rather than merged: two divergent chains cannot be
/// reconciled by a file copy, and the wrong outcome is a duplicated human
/// identity that ADR-0051 forbids.
///
/// # Errors
/// Fails if the bundle is absent, the key cannot open it, or a register already
/// exists at the destination.
pub fn restore(bundle: &Path, identity: &Path, into: &Paths) -> Result<Vec<String>> {
    crypt::detect()?;
    if !bundle.is_dir() {
        bail!(
            "no register bundle at {}; run `docket vault backup` on the authoritative node first",
            bundle.display()
        );
    }
    // Planned in full before anything is written, and refused if ANY target
    // exists.
    //
    // The first version of this guard tested `into.register()` alone. That file
    // is `register/issued.jsonl`, which does not exist until something has been
    // issued -- so a store holding three people and no documents looked empty,
    // and the second restore overwrote `people.jsonl` and silently discarded a
    // person allocated after the backup. A guard has to be about the files
    // being written, not about a file that stands for them.
    let mut queued = Vec::new();
    for entry in fs::read_dir(bundle).with_context(|| format!("reading {}", bundle.display()))? {
        let path = entry?.path();
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        let Some(stem) = name.strip_suffix(".age") else {
            // Anything not `.age` in the bundle is a defect under ADR-0071 §1,
            // and refusing beats restoring a file of unknown provenance.
            bail!(
                "{} is in the bundle without a .age extension (ADR-0071 §1)",
                path.display()
            );
        };
        // `register-issued.jsonl` was flattened from `register/issued.jsonl`
        // on the way in; the first hyphen is the directory separator.
        let relative = stem.replacen('-', "/", 1);
        queued.push((path, relative));
    }

    let occupied: Vec<&str> = queued
        .iter()
        .filter(|(_, rel)| into.store.join(rel).exists())
        .map(|(_, rel)| rel.as_str())
        .collect();
    if !occupied.is_empty() {
        bail!(
            "{} already holds {}. A restore does not merge: two append-only chains cannot be \
             reconciled by copying files, and overwriting discards every record made since the \
             backup -- one identifier ending up naming two people is what ADR-0051 forbids. \
             Move the existing store aside first",
            into.store.display(),
            occupied.join(", ")
        );
    }

    let mut restored = Vec::new();
    for (path, relative) in queued {
        let target = into.store.join(&relative);
        if let Some(dir) = target.parent() {
            fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        }
        let sealed = fs::read(&path).with_context(|| format!("reading {}", path.display()))?;
        let plain = crypt::decrypt_with_file(identity, &sealed)
            .with_context(|| format!("decrypting {}", path.display()))?;
        fs::write(&target, plain).with_context(|| format!("writing {}", target.display()))?;
        restored.push(relative);
    }

    if restored.is_empty() {
        bail!("{} holds no bundle files", bundle.display());
    }
    restored.sort();
    Ok(restored)
}

/// Verify a restored store: every chain intact, and no identifier reused.
///
/// Separate from `restore` so that the rehearsal ADR-0072 decision 6 requires
/// is a thing that can be *asserted*, not a thing the operator eyeballs.
///
/// # Errors
/// Fails if a chain cannot be read.
pub fn verify_restored(paths: &Paths) -> Result<Vec<String>> {
    let mut faults = Vec::new();
    let ledger = store::ledger(paths)?;
    for fault in chain::verify(&ledger)? {
        faults.push(format!("identity ledger {fault}"));
    }
    for fault in chain::verify(&store::events(paths)?)? {
        faults.push(format!("event log {fault}"));
    }
    for fault in chain::verify(&store::signatures(paths)?)? {
        faults.push(format!("signature ledger {fault}"));
    }
    if ledger.is_empty() {
        faults.push("the restored ledger is empty".to_owned());
    }
    Ok(faults)
}

/// The bundle path on a node, for callers that should not know the layout.
#[must_use]
pub fn bundle_path(paths: &Paths) -> PathBuf {
    paths.store.join("vault").join("_register")
}

/// One file considered for upload.
#[derive(Debug, Clone)]
pub struct Pushed {
    /// Path relative to the store.
    pub name: String,
    /// Whether the destination already held identical bytes.
    pub already_current: bool,
}

/// Copy the uploadable half of the store into a synced folder, guarding both ends.
///
/// DECISION-DEBT D-51 said the enforcement was "a human reading a list", and named
/// where the missing check belonged: *"a guard on the other side, in whatever
/// performs the upload, refusing any path outside `store/vault/`"*. This is that
/// guard. It decides nothing new -- ADR-0071 §1 makes the `.age` extension the
/// contract and §4 keeps names opaque; ADR-0072 D5 classifies every store path.
///
/// **Four refusals, and each one is a real upload accident.**
///
/// 1. A destination inside the store. The store is the thing being uploaded.
/// 2. Anything unclassified, or a register with no bundle behind it. Uploading a
///    store that `store status` calls incomplete publishes a half archive and
///    reports success.
/// 3. Any file that is not `.age`. One plaintext file in a sensitive tree is a
///    leak of personal data onto a foreign consumer drive.
/// 4. **A never-list directory already sitting in the destination.** This is the
///    only check that looks at what is ALREADY there rather than at what is being
///    sent, and it is the one that catches the accident that matters: a `keys/`
///    uploaded once, by hand, months ago. A versioned store retains what you
///    delete from it, so that key can never be destroyed -- and destroying it is
///    what erasure is.
///
/// # Errors
/// Fails on any of the four refusals, or if a file cannot be read or written.
pub fn push(paths: &Paths, dest: &Path) -> Result<Vec<Pushed>> {
    // Absolutised before comparing, and the reason is a real failure: a RELATIVE
    // `store/uploads` does not `starts_with` an absolute store path, so the guard
    // passed and the command wrote into the very directory it exists to protect.
    // Neither path is canonicalised -- the destination usually does not exist yet,
    // and `canonicalize` fails on a path that does not.
    let absolute = normalise(
        &(if dest.is_absolute() {
            dest.to_path_buf()
        } else {
            std::env::current_dir()
                .context("resolving the destination against the working directory")?
                .join(dest)
        }),
    );
    if absolute.starts_with(&paths.store) {
        bail!(
            "{} is inside the store, which is the thing being uploaded",
            absolute.display()
        );
    }

    // Refusal 4 first, and deliberately: it is about damage that is already done,
    // and adding more files to a folder that must be torn down anyway is wasted.
    let table = declared();
    for (name, disposition) in &table {
        if *disposition == Disposition::Never && absolute.join(name).exists() {
            bail!(
                "{} already holds {name}/, which must never be uploaded. A versioned store \
                 retains what you delete from it, so anything in there cannot be destroyed -- \
                 and for {name}/ specifically, destroying it is what erasure IS (ADR-0069). \
                 Remove it at the vendor, including every retained version, before uploading \
                 again",
                absolute.display()
            );
        }
    }

    let items = classify(paths)?;
    let stray: Vec<&str> = items
        .iter()
        .filter(|i| i.disposition == Disposition::Unclassified)
        .map(|i| i.name.as_str())
        .collect();
    if !stray.is_empty() {
        bail!(
            "nobody has said whether {} replicates. Classify it in node::declared() \
             (ADR-0072 D5) before uploading -- an upload that guesses is how a path ends up \
             published or lost by accident",
            stray.join(", ")
        );
    }
    let lost = unreplicated(paths)?;
    if !lost.is_empty() {
        bail!(
            "{} would be left behind: run `docket vault backup` first, or this upload publishes \
             a half archive and reports success",
            lost.join(", ")
        );
    }

    let source = paths.store.join("vault");
    if !source.is_dir() {
        bail!("nothing to upload: {} does not exist", source.display());
    }

    // EVERY file is checked before ANY file is written. The first version bailed
    // inside the copy loop while telling the operator "Nothing was uploaded" --
    // which was false for every file the walk had already reached, and a refusal
    // that misreports what it did is worse than no refusal at all.
    let files = walk(&source)?;
    let mut planned = Vec::new();
    for file in files {
        let relative = file
            .strip_prefix(&paths.store)
            .unwrap_or(&file)
            .to_string_lossy()
            .into_owned();
        if file.extension().and_then(|e| e.to_str()) != Some("age") {
            bail!(
                "{relative} is not .age. ADR-0071 §1 makes the extension the contract: a file \
                 in a sensitive tree without it is plaintext personal data on a foreign \
                 consumer drive. Nothing was uploaded"
            );
        }
        planned.push((file, relative));
    }

    let mut out = Vec::new();
    for (file, relative) in planned {
        let bytes = fs::read(&file).with_context(|| format!("reading {}", file.display()))?;
        let target = absolute.join(&relative);
        // Compared rather than copied blindly, so a re-run is cheap and the report
        // says what actually moved.
        let already_current = fs::read(&target).is_ok_and(|existing| existing == bytes);
        if !already_current {
            if let Some(dir) = target.parent() {
                fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
            }
            fs::write(&target, &bytes).with_context(|| format!("writing {}", target.display()))?;
        }
        out.push(Pushed {
            name: relative,
            already_current,
        });
    }

    if out.is_empty() {
        bail!("nothing to upload: {} holds no files", source.display());
    }
    out.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(out)
}

/// Resolve `.` and `..` lexically, without touching the filesystem.
///
/// `Path::starts_with` is purely lexical, so `/a/b/../../tmp/x` does not start
/// with `/tmp/x` and an inside-the-store destination expressed with `..` walked
/// straight past the guard. Not `canonicalize`, which fails on a path that does
/// not exist yet -- and an upload destination usually does not.
fn normalise(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for part in path.components() {
        match part {
            std::path::Component::ParentDir => {
                // At the root, `..` is the root. Popping nothing matches what the
                // kernel does rather than escaping above `/`.
                out.pop();
            }
            std::path::Component::CurDir => {}
            other => out.push(other),
        }
    }
    out
}

/// Every file under a directory, recursively.
fn walk(dir: &Path) -> Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    for entry in fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let path = entry?.path();
        if path.is_dir() {
            out.extend(walk(&path)?);
        } else {
            out.push(path);
        }
    }
    out.sort();
    Ok(out)
}
